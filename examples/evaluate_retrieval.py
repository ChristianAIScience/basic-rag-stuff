"""Measure Hit@k and MRR of every retrieval strategy on the labelled questions.

Run:  uv run python -m examples.evaluate_retrieval
      uv run python -m examples.evaluate_retrieval --details      (rank of the gold chunk per question)
(Requires: examples.generate_retrieval_dataset first, data ingested with REAL embeddings.)

Cost: one embedding call per question (cached across the five strategies) - no LLM judges involved.
"""

import argparse
from pathlib import Path

from rag_lab.config import load_settings
from rag_lab.db.chunks import fetch_all_chunks
from rag_lab.db.connection import get_engine
from rag_lab.db.vector_store import get_vector_store
from rag_lab.evaluation.question_generation import check_dataset, load_dataset
from rag_lab.evaluation.retrieval_metrics import evaluate_retriever
from rag_lab.models import get_embeddings
from rag_lab.retrieval.comparison import build_strategies
from rag_lab.tracking import enable_mlflow, log_results, mlflow_run, rag_params
from rag_lab.utils.cached_embeddings import QueryCachedEmbeddings

DEFAULT_DATASET = Path(__file__).resolve().parent.parent / "evaluation_data" / "retrieval_dataset.json"
K_VALUES = (1, 3, 5)
CUTOFF = max(K_VALUES)


def ids(results) -> list[str]:
    return [document.id for document, _ in results]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--dataset", type=Path, default=DEFAULT_DATASET)
    parser.add_argument("--details", action="store_true", help="print the gold chunk rank per question")
    args = parser.parse_args()

    settings = load_settings()
    info, examples = load_dataset(args.dataset)

    # Labels must still point at the same text: chunk ids survive re-ingestion with other chunking,
    # the stored text hash does not. Also rejects empty datasets and duplicate questions.
    problems = check_dataset(examples, fetch_all_chunks(settings))
    if problems:
        bullet_list = "".join(f"\n  - {problem}" for problem in problems)
        raise SystemExit(f"Cannot evaluate this dataset:{bullet_list}\nRun examples.generate_retrieval_dataset again.")

    # Five strategies search for the same questions: embed each question only once.
    embeddings = QueryCachedEmbeddings(get_embeddings(settings))
    vector_store = get_vector_store(get_engine(settings), embeddings, settings)
    category_of = {e.question: e.category for e in examples}  # unique: check_dataset rejects duplicates
    # The metadata filter gets the category of the gold chunk - an "oracle" filter: shows the upper bound of filtering.
    strategies = build_strategies(vector_store, k=CUTOFF, category_of=lambda q: category_of[q])

    print(f"{len(examples)} questions from {len({e.chunk_id for e in examples})} labelled chunks "
          f"(generated by {info['generator_model']}, seed {info['seed']})\n")
    use_mlflow = enable_mlflow(settings, experiment="retrieval-evaluation", tracing=False)
    dataset_params = {**rag_params(settings), "questions": len(examples), "dataset_seed": info["seed"],
                      "generator_model": info["generator_model"]}

    print(f"{'strategy':<24}" + "".join(f"{f'Hit@{k}':>9}" for k in K_VALUES) + f"{f'MRR@{CUTOFF}':>9}")
    all_scores = {}
    # One parent run per evaluation, one nested run per strategy -> compare strategies side by side in the UI.
    with mlflow_run(use_mlflow, run_name="retrieval-strategies"):
        if use_mlflow:
            log_results(params=dataset_params, metrics={})
        for strategy in strategies:
            scores = evaluate_retriever(lambda q: ids(strategy.search(q)), examples, K_VALUES)
            all_scores[strategy.name] = scores
            print(f"{strategy.name:<24}" + "".join(f"{scores.hit_at[k]:>9.2f}" for k in K_VALUES)
                  + f"{scores.mrr:>9.2f}")
            if use_mlflow:
                with mlflow_run(True, run_name=strategy.name, nested=True):
                    log_results(params={**dataset_params, "strategy": strategy.name}, metrics=scores.as_metrics())
    print("\nmetadata_filter uses the known category of the gold chunk (upper bound for metadata filtering).")

    if args.details:
        print(f"\nRank of the gold chunk per question (- = not in top {CUTOFF}):")
        print(f"  {'question':<60}" + "".join(f"{name[:10]:>11}" for name in all_scores))
        for i, example in enumerate(examples):
            ranks = [scores.gold_ranks[i] for scores in all_scores.values()]
            print(f"  {example.question[:60]:<60}" + "".join(f"{(r if r else '-'):>11}" for r in ranks))


if __name__ == "__main__":
    main()
