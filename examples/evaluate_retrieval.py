"""Measure Hit@k and MRR of every retrieval strategy on the labelled questions.

Run:  uv run python -m examples.evaluate_retrieval
      uv run python -m examples.evaluate_retrieval --details      (rank of the gold chunk per question)
(Requires: examples.generate_retrieval_dataset first, data ingested with REAL embeddings.)

Cost: only one embedding call per question and strategy - no LLM judges involved.
"""

import argparse
from pathlib import Path

from rag_lab.config import load_settings
from rag_lab.db.chunks import fetch_all_chunks
from rag_lab.db.connection import get_engine
from rag_lab.db.vector_store import get_vector_store
from rag_lab.evaluation.question_generation import load_dataset
from rag_lab.evaluation.retrieval_metrics import evaluate_retriever
from rag_lab.models import get_embeddings
from rag_lab.retrieval import hybrid, metadata_filter, mmr, score_threshold, similarity
from rag_lab.tracking import enable_mlflow, log_results, mlflow_run, rag_params

DEFAULT_DATASET = Path(__file__).resolve().parent.parent / "evaluation_data" / "retrieval_dataset.json"
K_VALUES = (1, 3, 5)
CUTOFF = max(K_VALUES)


def ids(results) -> list[str]:
    return [document.id for document, _ in results]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--dataset", type=Path, default=DEFAULT_DATASET)
    parser.add_argument("--details", action="store_true", help="print the gold chunk rank per question")
    args = parser.parse_args()

    settings = load_settings()
    info, examples = load_dataset(args.dataset)

    # The labels point to chunk ids - they must still exist (re-ingestion with another CHUNK_SIZE changes them).
    stored_ids = {chunk.id for chunk in fetch_all_chunks(settings)}
    missing = [e for e in examples if e.chunk_id not in stored_ids]
    if missing:
        raise SystemExit(f"{len(missing)} labelled chunks are no longer in the database "
                         "(chunking changed?). Run examples.generate_retrieval_dataset again.")
    if info["chunk_size"] != settings.chunk_size:
        print(f"Note: dataset was generated with chunk_size={info['chunk_size']}, now {settings.chunk_size}.")

    vector_store = get_vector_store(get_engine(settings), get_embeddings(settings), settings)
    category_of = {e.question: e.category for e in examples}
    strategies = {
        "similarity": lambda q: ids(similarity.similarity_search(vector_store, q, k=CUTOFF)),
        "mmr": lambda q: ids(mmr.mmr_search(vector_store, q, k=CUTOFF)),
        "score_threshold (0.4)": lambda q: ids(score_threshold.score_threshold_search(vector_store, q, 0.4, k=CUTOFF)),
        # Uses the category of the gold chunk - an "oracle" filter: shows the upper bound of filtering.
        "metadata_filter*": lambda q: ids(metadata_filter.metadata_filter_search(vector_store, q, category_of[q], k=CUTOFF)),
        "hybrid (RRF)": lambda q: ids(hybrid.hybrid_search(vector_store, q, k=CUTOFF)),
    }

    print(f"{len(examples)} questions from {len({e.chunk_id for e in examples})} labelled chunks "
          f"(generated by {info['generator_model']}, seed {info['seed']})\n")
    use_mlflow = enable_mlflow(settings, experiment="retrieval-evaluation", tracing=False)
    dataset_params = {**rag_params(settings), "questions": len(examples), "dataset_seed": info["seed"],
                      "generator_model": info["generator_model"]}

    print(f"{'strategy':<24}" + "".join(f"{f'Hit@{k}':>9}" for k in K_VALUES) + f"{f'MRR@{CUTOFF}':>9}")
    all_scores = {}
    # One parent run per evaluation, one nested run per strategy -> compare strategies side by side in the UI.
    with mlflow_run(use_mlflow, run_name="retrieval-strategies"):
        if use_mlflow:
            log_results(params=dataset_params, metrics={})
        for name, retriever in strategies.items():
            scores = evaluate_retriever(retriever, examples, K_VALUES)
            all_scores[name] = scores
            print(f"{name:<24}" + "".join(f"{scores.hit_at[k]:>9.2f}" for k in K_VALUES) + f"{scores.mrr:>9.2f}")
            if use_mlflow:
                with mlflow_run(True, run_name=name, nested=True):
                    log_results(params={**dataset_params, "strategy": name}, metrics=scores.as_metrics())
    print("\n* filter uses the known category of the gold chunk (upper bound for metadata filtering).")

    if args.details:
        print(f"\nRank of the gold chunk per question (- = not in top {CUTOFF}):")
        print(f"  {'question':<60}" + "".join(f"{name[:10]:>11}" for name in strategies))
        for i, example in enumerate(examples):
            ranks = [all_scores[name].gold_ranks[i] for name in strategies]
            print(f"  {example.question[:60]:<60}" + "".join(f"{(r if r else '-'):>11}" for r in ranks))


if __name__ == "__main__":
    main()
